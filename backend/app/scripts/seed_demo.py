"""
seed_demo.py — สร้างข้อมูล demo ให้ user เห็น flow ทันที (optional)

ต่างจาก seed.py (super_admin เท่านั้น) — script นี้สร้าง:
  - editor user (editor1 / editor123)
  - approver user (approver1 / approver123)
  - operator user (operator1 / operator123)
  - 3 devices (พร้อม pairing code)
  - 1 player group ที่รวมทุก device
  - 2 sample URL contents (อนุมัติแล้ว)
  - 1 sample presentation (fullscreen)
  - 1 sample plan
  - 1 sample schedule (active ตอนนี้ - ตลอดวันถัดไป)

รัน: docker compose exec backend python -m app.scripts.seed_demo

⚠ ห้ามรันบน production — มี password ที่เดาง่าย
"""
import asyncio
from datetime import UTC, datetime, timedelta

from sqlalchemy import select

from app.core.security import hash_password
from app.db import SessionLocal
from app.models.content import ApprovalStatus, Content, ContentType
from app.models.device import (
    Device,
    DevicePlatform,
    DeviceStatus,
    PlayerGroup,
    _gen_pairing_code,  # type: ignore[attr-defined]
)
from app.models.plan import Plan, PlanItem
from app.models.presentation import Presentation, PresentationZone
from app.models.schedule import Schedule, ScheduleStatus
from app.models.user import Role, User


async def _get_or_create_user(db, *, username, email, full_name, role, password):
    res = await db.execute(select(User).where(User.username == username))
    existing = res.scalar_one_or_none()
    if existing:
        print(f"  · user '{username}' มีอยู่แล้ว — skip")
        return existing
    user = User(
        username=username, email=email, full_name=full_name,
        role=role, is_active=True,
        password_hash=hash_password(password),
    )
    db.add(user)
    await db.flush()
    print(f"  + user '{username}' (role={role.value}) password='{password}'")
    return user


async def seed_demo() -> None:
    async with SessionLocal() as db:
        # ─── ตรวจสอบ super_admin มีก่อน (จาก seed.py) ───
        res = await db.execute(select(User).where(User.role == Role.SUPER_ADMIN))
        super_admin = res.scalar_one_or_none()
        if super_admin is None:
            print("✗ ยังไม่มี super_admin — รัน `python -m app.scripts.seed` ก่อน")
            return

        print("👥 Users:")
        await _get_or_create_user(
            db, username="editor1", email="editor1@demo.com",
            full_name="Demo Editor", role=Role.EDITOR, password="editor123",
        )
        await _get_or_create_user(
            db, username="approver1", email="approver1@demo.com",
            full_name="Demo Approver", role=Role.APPROVER, password="approver123",
        )
        await _get_or_create_user(
            db, username="operator1", email="operator1@demo.com",
            full_name="Demo Operator", role=Role.OPERATOR, password="operator123",
        )
        actor_id = super_admin.id

        # ─── Devices ───
        print("\n📺 Devices:")
        device_specs = [
            ("จอลอบบี้", "ชั้น 1 ทางเข้า", DevicePlatform.ANDROID_TV, "samsung"),
            ("จอโรงอาหาร", "ชั้น 1 โรงอาหาร", DevicePlatform.RPI_KIOSK, "lg"),
            ("จอห้องประชุม", "ชั้น 3 ห้องประชุมใหญ่", DevicePlatform.WEB_BROWSER, None),
        ]
        devices = []
        for name, location, platform, brand in device_specs:
            res = await db.execute(select(Device).where(Device.name == name))
            existing = res.scalar_one_or_none()
            if existing:
                print(f"  · device '{name}' มีอยู่แล้ว — skip")
                devices.append(existing)
                continue
            d = Device(
                name=name, location=location, platform=platform,
                tv_brand=brand, status=DeviceStatus.UNPAIRED,
                pairing_code=_gen_pairing_code(),
                pairing_code_expires_at=datetime.now(UTC) + timedelta(hours=24),
            )
            db.add(d)
            await db.flush()
            devices.append(d)
            print(f"  + device '{name}' pair-code={d.pairing_code}")

        # ─── Group ───
        print("\n📦 Group:")
        res = await db.execute(select(PlayerGroup).where(PlayerGroup.name == "ทุกจอใน demo"))
        group = res.scalar_one_or_none()
        if group is None:
            group = PlayerGroup(name="ทุกจอใน demo", description="auto-generated by seed_demo")
            group.devices = devices
            db.add(group)
            await db.flush()
            print(f"  + group '{group.name}' ({len(devices)} จอ)")
        else:
            print(f"  · group '{group.name}' มีอยู่แล้ว — skip")

        # ─── Contents ───
        print("\n🎞️ Contents:")
        content_specs = [
            ("ยินดีต้อนรับ", "https://example.com", ContentType.WEB),
            ("ข่าวสาร", "https://www.thairath.co.th/news", ContentType.WEB),
        ]
        contents = []
        for name, url, ctype in content_specs:
            res = await db.execute(select(Content).where(Content.name == name))
            existing = res.scalar_one_or_none()
            if existing:
                print(f"  · content '{name}' มีอยู่แล้ว — skip")
                contents.append(existing)
                continue
            now = datetime.now(UTC)
            c = Content(
                name=name, description=f"demo: {name}",
                type=ctype, url=url,
                approval_status=ApprovalStatus.APPROVED,
                approved_by=actor_id, approved_at=now,
                created_by=actor_id, is_active=True,
            )
            db.add(c)
            await db.flush()
            contents.append(c)
            print(f"  + content '{name}' ({ctype.value}) → approved")

        # ─── Presentation (fullscreen ใช้ content แรก) ───
        print("\n🎨 Presentation:")
        res = await db.execute(select(Presentation).where(Presentation.name == "หน้าจอต้อนรับ"))
        pres = res.scalar_one_or_none()
        if pres is None:
            pres = Presentation(
                name="หน้าจอต้อนรับ",
                description="fullscreen — content แรก",
                layout_json={
                    "template": "fullscreen",
                    "zones": [{"key": "main", "x": 0, "y": 0, "w": 100, "h": 100}],
                },
                duration_sec=20,
                created_by=actor_id,
            )
            pres.zones = [
                PresentationZone(
                    zone_key="main", content_id=contents[0].id,
                    params_json={}, order_index=0,
                ),
            ]
            db.add(pres)
            await db.flush()
            print(f"  + presentation '{pres.name}'")
        else:
            print(f"  · presentation '{pres.name}' มีอยู่แล้ว — skip")

        # ─── Plan ───
        print("\n📋 Plan:")
        res = await db.execute(select(Plan).where(Plan.name == "playlist demo"))
        plan = res.scalar_one_or_none()
        if plan is None:
            plan = Plan(name="playlist demo", description="auto-generated", created_by=actor_id)
            plan.items = [PlanItem(presentation_id=pres.id, order_index=0)]
            db.add(plan)
            await db.flush()
            print(f"  + plan '{plan.name}'")
        else:
            print(f"  · plan '{plan.name}' มีอยู่แล้ว — skip")

        # ─── Schedule (active ตลอด 7 วัน) ───
        print("\n📅 Schedule:")
        res = await db.execute(select(Schedule).where(Schedule.name == "schedule demo"))
        sched = res.scalar_one_or_none()
        if sched is None:
            now = datetime.now(UTC)
            sched = Schedule(
                name="schedule demo", description="auto-generated",
                plan_id=plan.id, player_group_id=group.id,
                start_at=now, end_at=now + timedelta(days=7),
                priority=500, status=ScheduleStatus.ACTIVE,
                created_by=actor_id, approved_by=actor_id, approved_at=now,
                is_active=True,
            )
            db.add(sched)
            print(f"  + schedule '{sched.name}' active 7d")
        else:
            print(f"  · schedule '{sched.name}' มีอยู่แล้ว — skip")

        await db.commit()
        print("\n✅ Demo data seeded")
        print("   ทดลอง pair player ด้วย pairing code ของ device ใดก็ได้")
        print("   หรือ login ด้วย editor1/approver1/operator1 เพื่อทดสอบ RBAC")


if __name__ == "__main__":
    asyncio.run(seed_demo())
